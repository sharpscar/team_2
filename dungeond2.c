void generate_monsters() {
    srand(time(NULL));  //srand((unsigned)time(NULL));과 같음
    while (count < MONSTER_COUNT) {  // 원하는 개수만큼 몬스터 배치
        int x = rand() % SIZE;  // 0 ~ SIZE-1 범위의 랜덤 x 좌표
        int y = rand() % SIZE;  // 0 ~ SIZE-1 범위의 랜덤 y 좌표
        
        if (dungeon1[y][x] == 0) {  // 빈 공간(0)일 경우에만 몬스터 배치
            dungeon1[y][x] = 9;  // 몬스터는 9로 표시
            monsters[count][0] = x;  // 몬스터 x 좌표 저장
            monsters[count][1] = y;  // 몬스터 y 좌표 저장
            count++;  // 배치된 몬스터 개수 증가
        }
    }
}

void dungeon_draw()
{
    system("clear");
    for (int y = 0; y < SIZE; y++)
    {
        for(int x = 0; x < SIZE; x++)
        {
            // printf("%d,", map[i][j]);
            if(me[1]==y && (me[0]==x))
            {
                printf("🙂 ");
            } else if(dungeon1[y][x]==1)
            {
                printf("🟫 ");     //벽
            } else if(dungeon1[y][x]==0)
            {
                printf("⬛ ");    //공백
            } else if(dungeon1[y][x]==9)
            {
                printf("🐉 ");    // 몬스터             
            }
        }
        printf("\n");
    }
}

void dungeon_move() {
    int next_x = me[0];
    int next_y = me[1];

    if (input == 'w' && me[1] > 0)
        next_y--;
    else if (input == 's' && me[1] < SIZE - 1)
        next_y++;
    else if (input == 'a' && me[0] > 0)
        next_x--;
    else if (input == 'd' && me[0] < SIZE - 1)
        next_x++;

    // 벽 체크: map[y][x] == 10 이면 벽
    if (dungeon1[next_y][next_x] != 10) {
        me[0] = next_x;
        me[1] = next_y;
    }

    input = ' ';
}

