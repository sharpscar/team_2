void move() {
    int next_x = me[0];
    int next_y = me[1];

    if (input == 'w' && me[1] > 0)
        next_y--;
    else if (input == 's' && me[1] < SIZE - 1)
        next_y++;
    else if (input == 'a' && me[0] > 0)
        next_x--;
    else if (input == 'd' && me[0] < SIZE - 1)
        next_x++;

    // 벽 체크: map[y][x] == 1 이면 벽
    if (map[next_y][next_x] != 1) { //1이 아니면 갑니다.
        me[0] = next_x;
        me[1] = next_y;
    }

    input = ' ';
}

